func Spec(f *Flat, ms []Machine) (*lex.Spec, error) {
	tokens, kind := numbered(f, func(a FlatActs) string { return a.Emit })
	does, act := numbered(f, func(a FlatActs) string { return a.Do })

	at := map[string]int{}

	for i, m := range ms {
		at[m.Scope] = i + 1
	}

	spec := &lex.Spec{Tokens: tokens, Does: does}

	for _, m := range ms {
		s := lex.Scope{Name: m.Scope, Start: int(m.DFA.Start())}

		for i := automaton.State(0); int(i) <= m.DFA.States(); i++ {
			row := make([]int, m.DFA.Classes().Len()+1)

			for c := range row {
				row[c] = int(m.DFA.Next(i, automaton.Class(c)))
			}

			s.Next = append(s.Next, row)
			s.Accept = append(s.Accept, int(m.DFA.Accept(i)))
		}

		for _, r := range m.Rules {
			a := lex.Act{Emit: kind[r.Acts.Emit], Do: act[r.Acts.Do], Pop: r.Acts.Pop}

			if r.Acts.Goto != "" {
				if a.Goto = at[r.Acts.Goto]; a.Goto == 0 {
					return nil, fmt.Errorf("%s:%d: -> %s, and there is no such scope", f.Path, r.Line, r.Acts.Goto)
				}
			}

			if r.Acts.Push != "" {
				if a.Push = at[r.Acts.Push]; a.Push == 0 {
					return nil, fmt.Errorf("%s:%d: returns to %s, and there is no such scope", f.Path, r.Line, r.Acts.Push)
				}
			}

			s.Acts = append(s.Acts, a)
		}

		spec.Scopes = append(spec.Scopes, s)
	}

	if len(ms) > 0 {
		spec.Ranges = ranges(ms[0].DFA.Classes())
	}

	for i := range ms {
		if got := ranges(ms[i].DFA.Classes()); !sameRanges(got, spec.Ranges) {
			return nil, fmt.Errorf("%s: %s reads a different alphabet; one file, one alphabet", f.Path, ms[i].Scope)
		}
	}

	return spec, nil
}

func numbered(f *Flat, of func(FlatActs) string) ([]string, map[string]int) {
	var out []string
	seen := map[string]bool{}

	for _, r := range f.Rules {
		if name := of(r.Acts); name != "" && !seen[name] {
			seen[name] = true
			out = append(out, name)
		}
	}

	sort.Strings(out)
	at := map[string]int{}

	for i, name := range out {
		at[name] = i + 1
	}

	return out, at
}

func ranges(c *automaton.Classes) []lex.Range {
	var out []lex.Range

	for i := 1; i <= c.Len(); i++ {
		for _, x := range c.Part(automaton.Class(i)).Ranges() {
			out = append(out, lex.Range{Lo: x.Lo, Hi: x.Hi, Class: i})
		}
	}

	sort.Slice(out, func(i, j int) bool { return out[i].Lo < out[j].Lo })

	return out
}

func sameRanges(a, b []lex.Range) bool {
	if len(a) != len(b) {
		return false
	}

	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}

	return true
}

func Go(spec *lex.Spec, pkg, from string) ([]byte, error) {
	if !token.IsIdentifier(pkg) || pkg == "_" {
		return nil, fmt.Errorf("%q cannot name a package", pkg)
	}

	toks, err := idents("Tok", spec.Tokens)

	if err != nil {
		return nil, err
	}

	does, err := idents("Do", spec.Does)

	if err != nil {
		return nil, err
	}

	var b bytes.Buffer

	fmt.Fprintf(&b, "// Code generated by genlex from %s. DO NOT EDIT.\n\npackage %s\n\n", from, pkg)
	b.WriteString("import \"github.com/cptaffe/automaton/lex\"\n\n")
	consts(&b, toks)
	consts(&b, does)
	b.WriteString("var Spec = &lex.Spec{\n")
	fmt.Fprintf(&b, "\tTokens: %#v,\n", spec.Tokens)

	if len(spec.Does) > 0 {
		fmt.Fprintf(&b, "\tDoes: %#v,\n", spec.Does)
	}

	b.WriteString("\tRanges: []lex.Range{\n")

	for _, r := range spec.Ranges {
		fmt.Fprintf(&b, "\t\t{Lo: %d, Hi: %d, Class: %d},\n", r.Lo, r.Hi, r.Class)
	}

	b.WriteString("\t},\n\tScopes: []lex.Scope{\n")

	for _, s := range spec.Scopes {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tName: %q, Start: %d,\n\t\t\tNext: [][]int{\n", s.Name, s.Start)

		for _, row := range s.Next {
			fmt.Fprintf(&b, "\t\t\t\t{%s},\n", list(row))
		}

		fmt.Fprintf(&b, "\t\t\t},\n\t\t\tAccept: []int{%s},\n\t\t\tActs: []lex.Act{\n", list(s.Accept))

		for _, a := range s.Acts {
			fmt.Fprintf(&b, "\t\t\t\t{%s},\n", fields(a))
		}

		b.WriteString("\t\t\t},\n\t\t},\n")
	}

	b.WriteString("\t},\n}\n")

	return format.Source(b.Bytes())
}

func consts(b *bytes.Buffer, names []string) {
	if len(names) == 0 {
		return
	}

	b.WriteString("const (\n")

	for i, n := range names {
		fmt.Fprintf(b, "\t%s = %d\n", n, i+1)
	}

	b.WriteString(")\n\n")
}

func list(xs []int) string {
	s := make([]string, len(xs))

	for i, x := range xs {
		s[i] = fmt.Sprint(x)
	}

	return strings.Join(s, ", ")
}

func fields(a lex.Act) string {
	var out []string

	for _, f := range []struct {
		name string
		v    int
	}{{"Emit", a.Emit}, {"Do", a.Do}, {"Goto", a.Goto}, {"Push", a.Push}} {
		if f.v != 0 {
			out = append(out, fmt.Sprintf("%s: %d", f.name, f.v))
		}
	}

	if a.Pop {
		out = append(out, "Pop: true")
	}

	return strings.Join(out, ", ")
}

func idents(prefix string, names []string) ([]string, error) {
	out := make([]string, len(names))
	by := map[string]string{}
	var errs []error

	for i, n := range names {
		id := prefix

		for _, part := range strings.FieldsFunc(n, func(r rune) bool { return r == '-' || r == '.' }) {
			rs := []rune(part)
			rs[0] = unicode.ToUpper(rs[0])
			id += string(rs)
		}

		switch was, ok := by[id]; {
		case !token.IsIdentifier(id) || id == prefix:
			errs = append(errs, fmt.Errorf("%s cannot name a Go constant", n))
		case ok:
			errs = append(errs, fmt.Errorf("%s and %s are both %s in Go", was, n, id))
		}

		by[id], out[i] = n, id
	}

	return out, errors.Join(errs...)
}
