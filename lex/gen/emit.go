package gen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"strings"
	"unicode"

	"github.com/cptaffe/automaton/fa"
)

func Go(f *Flat, ms []Machine, pkg, from string) ([]byte, error) {
	if !token.IsIdentifier(pkg) || pkg == "_" {
		return nil, fmt.Errorf("%q cannot name a package", pkg)
	}

	tokens, kind := numbered(f, func(a FlatActs) string { return a.Emit })
	does, do := numbered(f, func(a FlatActs) string { return a.Do })
	scopes := make([]string, 0, len(ms))

	for _, m := range ms {
		scopes = append(scopes, m.Scope)
	}

	toks, err1 := idents("Tok", tokens)
	dos, err2 := idents("Do", does)
	fns, err3 := idents("lex", scopes)

	if err := errors.Join(err1, err2, err3); err != nil {
		return nil, err
	}

	g := &writer{f: f, kind: kind, do: do, toks: toks, dos: dos, fn: map[string]string{}, tables: map[string]string{}}

	for i, s := range scopes {
		g.fn[s] = fns[i]
	}

	g.head(from, pkg, tokens)

	for _, m := range ms {
		if err := g.scope(m); err != nil {
			return nil, err
		}
	}

	g.b.WriteString(g.tail.String())

	return format.Source(g.b.Bytes())
}

type writer struct {
	f      *Flat
	b      bytes.Buffer
	tail   bytes.Buffer
	kind   map[string]int
	do     map[string]int
	toks   []string
	dos    []string
	fn     map[string]string
	tables map[string]string
	first  string
}

func (g *writer) head(from, pkg string, tokens []string) {
	b := &g.b
	fmt.Fprintf(b, "// Code generated by genlex from %s. DO NOT EDIT.\n\npackage %s\n\n", from, pkg)
	b.WriteString("import (\n\t\"io\"\n\t\"iter\"\n\n\t\"github.com/cptaffe/automaton/lex\"\n)\n\n")
	b.WriteString("type Tok int\n\n")

	if len(g.toks) > 0 {
		b.WriteString("const (\n")

		for i, n := range g.toks {
			fmt.Fprintf(b, "\t%s Tok = %d\n", n, i+1)
		}

		b.WriteString(")\n\n")
	}

	fmt.Fprintf(b, "var tokNames = %#v\n\n", append([]string{""}, tokens...))
	b.WriteString("func (t Tok) String() string {\n\tif t < 1 || int(t) >= len(tokNames) {\n\t\treturn \"\"\n\t}\n\n\treturn tokNames[t]\n}\n\n")

	if len(g.dos) > 0 {
		b.WriteString("const (\n")

		for i, n := range g.dos {
			fmt.Fprintf(b, "\t%s = %d\n", n, i+1)
		}

		b.WriteString(")\n\n")
	}

	b.WriteString("type stateFn func(*lexer) stateFn\n\n")
	b.WriteString("type lexer struct {\n\tlex.Emitter[Tok, stateFn]\n\tstate stateFn\n}\n\n")
}

func (g *writer) scope(m Machine) error {
	d, b := m.DFA, &g.b
	name := g.fn[m.Scope]

	if g.first == "" {
		g.first = name
		fmt.Fprintf(b, "func Lex(r io.Reader) lex.Tokens[Tok] {\n\treturn &lexer{Emitter: lex.NewEmitter[Tok, stateFn](r), state: %s}\n}\n\n", name)
		b.WriteString("func (l *lexer) Next() (lex.Token[Tok], bool) {\n\tfor !l.Ready() && l.state != nil {\n\t\tl.state = l.state(l)\n\t}\n\n\treturn l.Item()\n}\n\n")
		b.WriteString("func (l *lexer) All() iter.Seq[lex.Token[Tok]] {\n\treturn func(yield func(lex.Token[Tok]) bool) {\n\t\tfor t, ok := l.Next(); ok && yield(t); t, ok = l.Next() {\n\t\t}\n\t}\n}\n\n")
	}

	quiet := quietStates(d, m.Rules)
	used := map[fa.State]bool{}

	for s := range d.All() {
		for to := range d.Edges(s) {
			used[to] = true
		}
	}

	fmt.Fprintf(b, "func %s(l *lexer) stateFn {\n\tif l.Begin() {\n\t\tl.End(%q)\n\n\t\treturn nil\n\t}\n\n\tvar r rune\n\n", name, m.Scope)

	order := []fa.State{d.Start()}

	for s := range d.All() {
		if s != d.Start() {
			order = append(order, s)
		}
	}

	for _, s := range order {
		g.state(d, s, used[s], quiet[s])
	}

	b.WriteString("done:\n\tswitch l.Back() {\n")

	for _, a := range d.Accepted() {
		if err := g.act(m, int(a)); err != nil {
			return err
		}
	}

	fmt.Fprintf(b, "\t}\n\n\tl.Fail(%q)\n\n\treturn nil\n}\n\n", m.Scope)

	return nil
}

func (g *writer) state(d *fa.DFA[rune], s fa.State, used, quiet bool) {
	b := &g.b

	if used {
		fmt.Fprintf(b, "s%d:\n", s)
	}

	fmt.Fprintf(b, "\tl.Quiet(%t)\n", quiet)

	if a := d.Accept(s); a != fa.NoMatch && s != d.Start() {
		fmt.Fprintf(b, "\tl.Mark(%d)\n", a)
	}

	var cases bytes.Buffer

	for to, set := range d.Edges(s) {
		fmt.Fprintf(&cases, "\tcase %s:\n\t\tgoto s%d\n", g.cond(set), to)
	}

	if cases.Len() > 0 {
		fmt.Fprintf(b, "\tr = l.Step()\n\tswitch {\n%s\t}\n", cases.String())
	}

	b.WriteString("\tgoto done\n")
}

func (g *writer) act(m Machine, rule int) error {
	r, b := m.Rules[rule-1], &g.b
	next := g.fn[m.Scope]
	fmt.Fprintf(b, "\tcase %d:\n", rule)

	if r.Acts.Push != "" {
		at, ok := g.fn[r.Acts.Push]

		if !ok {
			return fmt.Errorf("%s:%d: returns to %s, and there is no such scope", g.f.Path, r.Line, r.Acts.Push)
		}

		fmt.Fprintf(b, "\t\tl.Push(%s)\n", at)
	}

	switch {
	case r.Acts.Pop:
		fmt.Fprintf(b, "\t\tnext, ok := l.Pop(%q)\n\n\t\tif !ok {\n\t\t\treturn nil\n\t\t}\n\n", m.Scope)
		next = "next"
	case r.Acts.Goto != "":
		at, ok := g.fn[r.Acts.Goto]

		if !ok {
			return fmt.Errorf("%s:%d: -> %s, and there is no such scope", g.f.Path, r.Line, r.Acts.Goto)
		}

		next = at
	}

	if k := g.kind[r.Acts.Emit]; k != 0 {
		do := "0"

		if n := g.do[r.Acts.Do]; n != 0 {
			do = g.dos[n-1]
		}

		fmt.Fprintf(b, "\t\tl.Emit(%s, %s)\n\n", g.toks[k-1], do)
	} else {
		b.WriteString("\t\tl.Skip()\n\n")
	}

	fmt.Fprintf(b, "\t\treturn %s\n", next)

	return nil
}

func (g *writer) cond(set fa.Set[rune]) string {
	rs := set.Ranges()

	if len(rs) > 4 {
		return fmt.Sprintf("lex.In(%s, r)", g.table(rs))
	}

	parts := make([]string, 0, len(rs))

	for _, x := range rs {
		if x.Lo == x.Hi {
			parts = append(parts, "r == "+lit(x.Lo))
		} else {
			parts = append(parts, lit(x.Lo)+" <= r && r <= "+lit(x.Hi))
		}
	}

	return strings.Join(parts, " || ")
}

func (g *writer) table(rs []fa.Range[rune]) string {
	var key strings.Builder

	for _, x := range rs {
		fmt.Fprintf(&key, "{Lo: %s, Hi: %s}, ", lit(x.Lo), lit(x.Hi))
	}

	if name, ok := g.tables[key.String()]; ok {
		return name
	}

	name := fmt.Sprintf("ranges%d", len(g.tables)+1)
	g.tables[key.String()] = name
	fmt.Fprintf(&g.tail, "var %s = []lex.Range{%s}\n\n", name, key.String())

	return name
}

func lit(r rune) string {
	if r < unicode.MaxASCII && unicode.IsPrint(r) {
		return fmt.Sprintf("%q", r)
	}

	return fmt.Sprintf("0x%x", r)
}

func quietStates(d *fa.DFA[rune], rules []FlatRule) map[fa.State]bool {
	loud := map[fa.State]bool{}

	for s := range d.All() {
		if a := d.Accept(s); a != fa.NoMatch && rules[a-1].Acts.Emit != "" {
			loud[s] = true
		}
	}

	for changed := true; changed; {
		changed = false

		for s := range d.All() {
			if loud[s] {
				continue
			}

			for to := range d.Edges(s) {
				if loud[to] {
					loud[s], changed = true, true

					break
				}
			}
		}
	}

	quiet := map[fa.State]bool{}

	for s := range d.All() {
		quiet[s] = !loud[s]
	}

	return quiet
}

func numbered(f *Flat, of func(FlatActs) string) ([]string, map[string]int) {
	var out []string
	seen := map[string]bool{}

	for _, r := range f.Rules {
		if name := of(r.Acts); name != "" && !seen[name] {
			seen[name] = true
			out = append(out, name)
		}
	}

	slices.Sort(out)
	at := map[string]int{}

	for i, name := range out {
		at[name] = i + 1
	}

	return out, at
}

func idents(prefix string, names []string) ([]string, error) {
	out := make([]string, len(names))
	by := map[string]string{}
	var errs []error

	for i, n := range names {
		id := prefix

		for _, part := range strings.FieldsFunc(n, func(r rune) bool { return strings.ContainsRune("-.()", r) }) {
			rs := []rune(part)
			rs[0] = unicode.ToUpper(rs[0])
			id += string(rs)
		}

		switch was, ok := by[id]; {
		case !token.IsIdentifier(id) || id == prefix:
			errs = append(errs, fmt.Errorf("%s cannot name a Go identifier", n))
		case ok:
			errs = append(errs, fmt.Errorf("%s and %s are both %s in Go", was, n, id))
		}

		by[id], out[i] = n, id
	}

	return out, errors.Join(errs...)
}
