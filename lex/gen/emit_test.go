func TestTheTableIsGoThatDeclaresTheSpec(t *testing.T) {
	given := &lex.Spec{
		Tokens: []string{"close.paren", "open-paren", "word"},
		Does:   []string{"name"},
		Ranges: []lex.Range{{Lo: '(', Hi: '(', Class: 2}, {Lo: 'a', Hi: 'z', Class: 1}},
		Scopes: []lex.Scope{{
			Name:  "start",
			Start: 1,
			States: []lex.State{
				{Next: []int{0, 0, 0}},
				{Next: []int{0, 2, 3}},
				{Next: []int{0, 2, 0}, Accept: 1},
				{Next: []int{0, 0, 0}, Accept: 2},
			},
			Acts: []lex.Act{{Emit: 3, Do: 1}, {Emit: 2, Goto: 1, Push: 1}, {Pop: true}},
		}},
	}

	src, err := gen.Go(given, "scan", "t.lex")

	if err != nil {
		t.Fatal(err)
	}

	file, err := parser.ParseFile(token.NewFileSet(), "scan.gen.go", src, parser.ParseComments)

	if err != nil {
		t.Fatalf("%v\n%s", err, src)
	}

	if got, want := file.Comments[0].Text(), "Code generated by genlex from t.lex. DO NOT EDIT.\n"; got != want {
		t.Errorf("the header is %q; want %q", got, want)
	}

	if got := file.Name.Name; got != "scan" {
		t.Errorf("the package is %s; want scan", got)
	}

	if got, want := declared(t, file), []string{
		"const TokCloseParen = 1",
		"const TokOpenParen = 2",
		"const TokWord = 3",
		"const DoName = 1",
		"var Spec = &lex.Spec{...}",
	}; !reflect.DeepEqual(got, want) {
		t.Errorf("the file declares %q; want %q", got, want)
	}

	if got, want := fields(t, file), []string{
		`Tokens: []string{"close.paren", "open-paren", "word"}`,
		`Does: []string{"name"}`,
		"Ranges: []lex.Range{{Lo: 40, Hi: 40, Class: 2}, {Lo: 97, Hi: 122, Class: 1}}",
		`Scopes: []lex.Scope{{Name: "start", Start: 1, States: []lex.State{{Next: []int{0, 0, 0}}, {Next: []int{0, 2, 3}}, {Next: []int{0, 2, 0}, Accept: 1}, {Next: []int{0, 0, 0}, Accept: 2}}, Acts: []lex.Act{{Emit: 3, Do: 1}, {Emit: 2, Goto: 1, Push: 1}, {Pop: true}}}}`,
	}; !reflect.DeepEqual(got, want) {
		t.Errorf("the spec holds\n%q\nwant\n%q", got, want)
	}
}

func TestATableWithNoDoesLeavesThemOut(t *testing.T) {
	given := &lex.Spec{Tokens: []string{"word"}}

	src, err := gen.Go(given, "scan", "t.lex")

	if err != nil {
		t.Fatal(err)
	}

	file, err := parser.ParseFile(token.NewFileSet(), "scan.gen.go", src, 0)

	if err != nil {
		t.Fatalf("%v\n%s", err, src)
	}

	if got, want := fields(t, file), []string{`Tokens: []string{"word"}`, "Ranges: []lex.Range{}", "Scopes: []lex.Scope{}"}; !reflect.DeepEqual(got, want) {
		t.Errorf("the spec holds %q; want %q", got, want)
	}
}

func TestTheTableRefusesNamesGoCannotSpell(t *testing.T) {
	for _, c := range []struct {
		name  string
		given lex.Spec
		when  string
		then  string
	}{
		{"no package", lex.Spec{}, "", `"" cannot name a package`},
		{"the blank package", lex.Spec{}, "_", `"_" cannot name a package`},
		{"a package that is not a word", lex.Spec{}, "a-b", `"a-b" cannot name a package`},
		{"two tokens that are one constant", lex.Spec{Tokens: []string{"a-b", "aB"}}, "scan", "a-b and aB are both TokAB in Go"},
		{"a token with no letters", lex.Spec{Tokens: []string{"-"}}, "scan", "- cannot name a Go constant"},
		{"a do with no letters", lex.Spec{Does: []string{"."}}, "scan", ". cannot name a Go constant"},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := gen.Go(&c.given, c.when, "t.lex")

			if err == nil || err.Error() != c.then {
				t.Errorf("the refusal is %v; want %q", err, c.then)
			}
		})
	}
}

func declared(t *testing.T, file *ast.File) []string {
	t.Helper()

	var out []string

	for _, d := range file.Decls {
		g, ok := d.(*ast.GenDecl)

		if !ok || g.Tok == token.IMPORT {
			continue
		}

		for _, s := range g.Specs {
			v := s.(*ast.ValueSpec)
			value := show(t, v.Values[0])

			if at := strings.Index(value, "{"); at >= 0 {
				value = value[:at] + "{...}"
			}

			out = append(out, g.Tok.String()+" "+v.Names[0].Name+" = "+value)
		}
	}

	return out
}

func fields(t *testing.T, file *ast.File) []string {
	t.Helper()

	var out []string

	for _, d := range file.Decls {
		g, ok := d.(*ast.GenDecl)

		if !ok || g.Tok != token.VAR {
			continue
		}

		spec := g.Specs[0].(*ast.ValueSpec).Values[0].(*ast.UnaryExpr).X.(*ast.CompositeLit)

		for _, e := range spec.Elts {
			out = append(out, show(t, e))
		}
	}

	return out
}

func show(t *testing.T, n ast.Node) string {
	t.Helper()

	var b bytes.Buffer

	if err := format.Node(&b, token.NewFileSet(), n); err != nil {
		t.Fatal(err)
	}

	flat := strings.NewReplacer(",\n", ", ", "{\n", "{").Replace(b.String())

	return strings.Join(strings.Fields(flat), " ")
}
