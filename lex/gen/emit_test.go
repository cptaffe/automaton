func TestTheGoIsFormattedAndDeclaresTheLexer(t *testing.T) {
	for _, c := range []struct {
		name  string
		given string
		then  []string
	}{
		{
			"tokens and a do",
			"start {\n  \"(\"  emit open-paren\n  \")\"  emit close.paren\n  [a-z]+  emit word do name\n}\n",
			[]string{
				"type Tok int",
				"const TokCloseParen Tok = 1",
				"const TokOpenParen Tok = 2",
				"const TokWord Tok = 3",
				"func (t Tok) String() string",
				"const DoName = 1",
				"func Lex(ctx context.Context, r io.Reader) <-chan lex.Token[Tok]",
			},
		},
		{
			"no do",
			"start {\n  [a-z]+  emit word\n}\n",
			[]string{
				"type Tok int",
				"const TokWord Tok = 1",
				"func (t Tok) String() string",
				"func Lex(ctx context.Context, r io.Reader) <-chan lex.Token[Tok]",
			},
		},
	} {
		t.Run(c.name, func(t *testing.T) {
			flat, ms := lextest.Build(t, c.given)

			src, err := gen.Go(flat, ms, "scan", "t.lex")

			if err != nil {
				t.Fatal(err)
			}

			if formatted, err := format.Source(src); err != nil || !bytes.Equal(formatted, src) {
				t.Errorf("the Go is not gofmt'd: %v\n%s", err, src)
			}

			file, err := parser.ParseFile(token.NewFileSet(), "scan.gen.go", src, parser.ParseComments)

			if err != nil {
				t.Fatalf("%v\n%s", err, src)
			}

			if got, want := file.Comments[0].Text(), "Code generated by genlex from t.lex. DO NOT EDIT.\n"; got != want {
				t.Errorf("the header is %q; want %q", got, want)
			}

			if got := file.Name.Name; got != "scan" {
				t.Errorf("the package is %s; want scan", got)
			}

			if got := exported(t, file); !reflect.DeepEqual(got, c.then) {
				t.Errorf("the file declares\n%q\nwant\n%q", got, c.then)
			}
		})
	}
}

func TestTheGoRefusesNamesGoCannotSpell(t *testing.T) {
	emits := func(names ...string) *gen.Flat {
		f := &gen.Flat{Path: "t.lex", Rules: make([]gen.FlatRule, 0, len(names))}

		for _, n := range names {
			f.Rules = append(f.Rules, gen.FlatRule{Acts: gen.FlatActs{Emit: n}})
		}

		return f
	}

	for _, c := range []struct {
		name   string
		given  *gen.Flat
		scopes []gen.Machine
		when   string
		then   string
	}{
		{"no package", &gen.Flat{}, nil, "", `"" cannot name a package`},
		{"the blank package", &gen.Flat{}, nil, "_", `"_" cannot name a package`},
		{"a package that is not a word", &gen.Flat{}, nil, "a-b", `"a-b" cannot name a package`},
		{"two tokens that are one identifier", emits("a-b", "aB"), nil, "scan", "a-b and aB are both TokAB in Go"},
		{"a token with no letters", emits("-"), nil, "scan", "- cannot name a Go identifier"},
		{"a do with no letters", &gen.Flat{Rules: []gen.FlatRule{{Acts: gen.FlatActs{Emit: "x", Do: "."}}}}, nil, "scan", ". cannot name a Go identifier"},
		{"two scopes that are one identifier", &gen.Flat{}, []gen.Machine{{Scope: "a-b"}, {Scope: "aB"}}, "scan", "a-b and aB are both lexAB in Go"},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := gen.Go(c.given, c.scopes, c.when, "t.lex")

			if err == nil || err.Error() != c.then {
				t.Errorf("the refusal is %v; want %q", err, c.then)
			}
		})
	}
}

func exported(t *testing.T, file *ast.File) []string {
	t.Helper()

	var out []string

	for _, d := range file.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			if d.Name.IsExported() {
				out = append(out, show(t, &ast.FuncDecl{Recv: d.Recv, Name: d.Name, Type: d.Type}))
			}
		case *ast.GenDecl:
			for _, s := range d.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						out = append(out, "type "+show(t, s))
					}
				case *ast.ValueSpec:
					if s.Names[0].IsExported() {
						out = append(out, d.Tok.String()+" "+show(t, s))
					}
				}
			}
		}
	}

	return out
}

func show(t *testing.T, n ast.Node) string {
	t.Helper()

	var b bytes.Buffer

	if err := format.Node(&b, token.NewFileSet(), n); err != nil {
		t.Fatal(err)
	}

	return strings.Join(strings.Fields(b.String()), " ")
}
