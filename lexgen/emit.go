package lexgen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"

	"github.com/cptaffe/automaton"
	"github.com/cptaffe/automaton/lexrun"
)

func Spec(f *Flat, ms []Machine) (*lexrun.Spec, []string) {
	var tokens []string
	seen := map[string]bool{}

	for _, r := range f.Rules {
		if r.Acts.Emit != "" && !seen[r.Acts.Emit] {
			seen[r.Acts.Emit] = true
			tokens = append(tokens, r.Acts.Emit)
		}
	}

	sort.Strings(tokens)
	kind := map[string]int{}

	for i, t := range tokens {
		kind[t] = i
	}

	var does []string
	did := map[string]bool{}

	for _, r := range f.Rules {
		if r.Acts.Do != "" && !did[r.Acts.Do] {
			did[r.Acts.Do] = true
			does = append(does, r.Acts.Do)
		}
	}

	sort.Strings(does)
	act := map[string]int{}

	for i, d := range does {
		act[d] = i
	}

	at := map[string]int{}

	for i, m := range ms {
		at[m.Scope] = i
	}

	spec := &lexrun.Spec{Tokens: tokens}

	for _, m := range ms {
		s := lexrun.Scope{Name: m.Scope, Start: int(m.DFA.Start())}

		for i := automaton.State(0); int(i) < m.DFA.States(); i++ {
			row := make([]int, m.DFA.Classes().Len())

			for c := range row {
				row[c] = int(m.DFA.Next(i, automaton.Class(c)))
			}

			s.Next = append(s.Next, row)
			s.Accept = append(s.Accept, int(m.DFA.Accept(i)))
		}

		for _, r := range m.Rules {
			a := lexrun.Act{Emit: lexrun.None, Do: lexrun.None, Goto: lexrun.None, Drop: r.Acts.Drop}

			if r.Acts.Emit != "" {
				a.Emit = kind[r.Acts.Emit]
			}

			if r.Acts.Do != "" {
				a.Do = act[r.Acts.Do]
			}

			if r.Acts.Goto != "" {
				to, ok := at[r.Acts.Goto]

				if !ok {
					return nil, []string{fmt.Sprintf("%s:%d: -> %s, and there is no such scope", f.Name, r.Line, r.Acts.Goto)}
				}

				a.Goto = to
			}

			s.Acts = append(s.Acts, a)
		}

		spec.Scopes = append(spec.Scopes, s)
	}

	if len(ms) > 0 {
		spec.Ranges = ranges(ms[0].DFA.Classes())
	}

	for i := range ms {
		if got := ranges(ms[i].DFA.Classes()); !sameRanges(got, spec.Ranges) {
			return nil, []string{fmt.Sprintf("%s: %s reads a different alphabet; one file, one alphabet", f.Name, ms[i].Scope)}
		}
	}

	return spec, nil
}

func ranges(c *automaton.Classes) []lexrun.Range {
	var out []lexrun.Range

	for i, p := range c.Parts() {
		for _, x := range p.Ranges() {
			out = append(out, lexrun.Range{Lo: x.Lo, Hi: x.Hi, Class: i})
		}
	}

	sort.Slice(out, func(i, j int) bool { return out[i].Lo < out[j].Lo })

	return out
}

func sameRanges(a, b []lexrun.Range) bool {
	if len(a) != len(b) {
		return false
	}

	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}

	return true
}

func Go(f *Flat, spec *lexrun.Spec, pkg string) []byte {
	var b bytes.Buffer

	fmt.Fprintf(&b, "// Code generated by genlex from %s.lex. DO NOT EDIT.\n\npackage %s\n\n", f.Name, pkg)
	b.WriteString("import \"github.com/cptaffe/automaton/lexrun\"\n\nconst (\n")

	for i, t := range spec.Tokens {
		fmt.Fprintf(&b, "\t%s = %d\n", ident(t), i)
	}

	b.WriteString(")\n\nvar Spec = &lexrun.Spec{\n\tTokens: []string{")

	for i, t := range spec.Tokens {
		if i > 0 {
			b.WriteString(", ")
		}

		fmt.Fprintf(&b, "%q", t)
	}

	b.WriteString("},\n\tRanges: []lexrun.Range{\n")

	for _, r := range spec.Ranges {
		fmt.Fprintf(&b, "\t\t{Lo: %d, Hi: %d, Class: %d},\n", r.Lo, r.Hi, r.Class)
	}

	b.WriteString("\t},\n\tScopes: []lexrun.Scope{\n")

	for _, s := range spec.Scopes {
		fmt.Fprintf(&b, "\t\t{\n\t\t\tName: %q, Start: %d,\n\t\t\tNext: [][]int{\n", s.Name, s.Start)

		for _, row := range s.Next {
			b.WriteString("\t\t\t\t{")

			for i, to := range row {
				if i > 0 {
					b.WriteString(", ")
				}

				fmt.Fprintf(&b, "%d", to)
			}

			b.WriteString("},\n")
		}

		b.WriteString("\t\t\t},\n\t\t\tAccept: []int{")

		for i, a := range s.Accept {
			if i > 0 {
				b.WriteString(", ")
			}

			fmt.Fprintf(&b, "%d", a)
		}

		b.WriteString("},\n\t\t\tActs: []lexrun.Act{\n")

		for _, a := range s.Acts {
			fmt.Fprintf(&b, "\t\t\t\t{Emit: %s, Do: %s, Goto: %s, Drop: %t},\n",
				some(a.Emit), some(a.Do), some(a.Goto), a.Drop)
		}

		b.WriteString("\t\t\t},\n\t\t},\n")
	}

	b.WriteString("\t},\n}\n")

	if out, err := format.Source(b.Bytes()); err == nil {
		return out
	}

	return b.Bytes()
}

func some(v int) string {
	if v == lexrun.None {
		return "lexrun.None"
	}

	return fmt.Sprint(v)
}

func ident(s string) string {
	out := []rune("Tok")
	up := true

	for _, r := range s {
		if r == '-' {
			up = true

			continue
		}

		if up && r >= 'a' && r <= 'z' {
			r = r - 'a' + 'A'
		}

		up = false
		out = append(out, r)
	}

	return string(out)
}
