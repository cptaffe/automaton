package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/cptaffe/automaton/lex/gen"
	"golang.org/x/tools/txtar"
)

var ident = regexp.MustCompile(`^[a-z][a-z0-9]*$`)

func main() {
	out := flag.String("o", "", "the directory to write the cases into")
	path := flag.String("import", "", "the import path of that directory")
	flag.Parse()

	if err := run(*out, *path, flag.Args()); err != nil {
		fmt.Fprintf(os.Stderr, "lexcases: %v\n", err)
		os.Exit(1)
	}
}

func run(out, path string, files []string) error {
	if out == "" || path == "" || len(files) == 0 {
		return fmt.Errorf("usage: lexcases -o dir -import path file.txtar")
	}

	var all []txtar.File

	for _, f := range files {
		a, err := txtar.ParseFile(f)

		if err != nil {
			return err
		}

		all = append(all, a.Files...)
	}

	if err := os.RemoveAll(out); err != nil {
		return err
	}

	names := make([]string, 0, len(all))

	for _, c := range all {
		if !ident.MatchString(c.Name) || slices.Contains(names, c.Name) {
			return fmt.Errorf("%s: a case needs a new lower-case name", c.Name)
		}

		if err := write(filepath.Join(out, c.Name), c); err != nil {
			return err
		}

		names = append(names, c.Name)
	}

	return registry(out, path, names)
}

func write(dir string, c txtar.File) error {
	parsed, err := gen.Parse(bytes.NewReader(c.Data), c.Name+".lex")

	if err != nil {
		return err
	}

	flat, err := gen.Expand(parsed)

	if err != nil {
		return err
	}

	ms, _, err := gen.Build(flat, 0)

	if err != nil {
		return err
	}

	src, err := gen.Go(flat, ms, c.Name, c.Name+".lex")

	if err != nil {
		return fmt.Errorf("%s: %w", c.Name, err)
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	return os.WriteFile(filepath.Join(dir, "scan.gen.go"), src, 0o644)
}

func registry(out, path string, names []string) error {
	var b strings.Builder

	fmt.Fprintf(&b, "// Code generated by lexcases. DO NOT EDIT.\n\npackage %s\n\nimport (\n", filepath.Base(out))
	b.WriteString("\t\"github.com/cptaffe/automaton/internal/lextest\"\n")

	for _, n := range names {
		fmt.Fprintf(&b, "\t%q\n", path+"/"+n)
	}

	b.WriteString(")\n\nvar Lexers = map[string]lextest.Lexer{\n")

	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: lextest.Of(%s.Lex),\n", n, n)
	}

	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))

	if err != nil {
		return err
	}

	return os.WriteFile(filepath.Join(out, "cases.go"), src, 0o644)
}
