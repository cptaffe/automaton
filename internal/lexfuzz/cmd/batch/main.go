package main

import (
	"flag"
	"fmt"
	"math/rand/v2"
	"os"
	"path/filepath"

	"github.com/cptaffe/automaton/internal/lextest"
	"github.com/cptaffe/automaton/internal/regextest"
	"golang.org/x/tools/txtar"
)

func main() {
	n := flag.Int("n", 100, "how many lexers to write")
	seed := flag.Uint64("seed", 1, "the seed the grammars grow from")
	dir := flag.String("dir", ".", "the package to write")
	path := flag.String("import", "", "the import path of that package")
	flag.Parse()

	if err := run(*n, *seed, *dir, *path); err != nil {
		fmt.Fprintf(os.Stderr, "batch: %v\n", err)
		os.Exit(1)
	}
}

func run(n int, seed uint64, dir, path string) error {
	if path == "" {
		return fmt.Errorf("usage: batch -n count -seed n -dir dir -import path")
	}

	rnd := rand.New(rand.NewPCG(seed, seed))
	var lexers, patterns txtar.Archive
	lexers.Comment = fmt.Appendf(nil, "%d lexers grown from seed %d.\n", n, seed)

	for len(lexers.Files) < n {
		data := make([]byte, 2+rnd.IntN(10))

		for i := range data {
			data[i] = byte(rnd.IntN(8))
		}

		p := regextest.Decode(data)
		src := "start {\n  " + p.Lex + "  emit x\n  any  ignore\n}\n"

		if lextest.Error(src) != nil {
			continue
		}

		name := fmt.Sprintf("l%d", len(lexers.Files)+1)
		lexers.Files = append(lexers.Files, txtar.File{Name: name, Data: []byte(src)})
		patterns.Files = append(patterns.Files, txtar.File{Name: name, Data: []byte(p.Regexp + "\n")})
	}

	if err := os.MkdirAll(filepath.Join(dir, "testdata"), 0o755); err != nil {
		return err
	}

	for name, a := range map[string]*txtar.Archive{"lexers.txtar": &lexers, "patterns.txtar": &patterns} {
		if err := os.WriteFile(filepath.Join(dir, "testdata", name), txtar.Format(a), 0o644); err != nil {
			return err
		}
	}

	pkg := filepath.Base(path)
	src := fmt.Sprintf(test, pkg, path)

	return os.WriteFile(filepath.Join(dir, "batch_test.go"), []byte(src), 0o644)
}

const test = `// Code generated by batch. DO NOT EDIT.

package %s

import (
	"reflect"
	"regexp"
	"strings"
	"testing"

	"github.com/cptaffe/automaton/internal/lextest"
	"github.com/cptaffe/automaton/internal/regextest"
	"%s/internal/cases"
	"golang.org/x/tools/txtar"
)

func longest(re *regexp.Regexp, text string) []string {
	var out []string
	for at := 0; at < len(text); {
		if m := re.FindStringIndex(text[at:]); m != nil && m[1] > 0 {
			out = append(out, "x("+text[at:at+m[1]]+")")
			at += m[1]
			continue
		}
		at++
	}
	return out
}

func TestEachLexerReadsWhatItsRegexpMatches(t *testing.T) {
	a, err := txtar.ParseFile("testdata/patterns.txtar")
	if err != nil {
		t.Fatal(err)
	}
	words := regextest.Words(4)
	for _, f := range a.Files {
		src := strings.TrimSuffix(string(f.Data), "\n")
		re := regexp.MustCompile("^(?:" + src + ")")
		re.Longest()
		lx := cases.Lexers[f.Name]
		t.Run(f.Name, func(t *testing.T) {
			for _, w := range words {
				got, err := lextest.Read(t, lx, w)
				if want := longest(re, w); err != nil || !reflect.DeepEqual(got, want) && len(got)+len(want) > 0 {
					t.Fatalf("%%s on %%q: lex read %%q, %%v; regexp %%q", src, w, got, err, want)
				}
			}
		})
	}
}
`
